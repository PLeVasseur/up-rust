class WorkflowDumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def readable_string(dumper, value):
    return dumper.represent_scalar('tag:yaml.org,2002:str', value, style='|' if '\n' in value else None)


WorkflowDumper.add_representer(str, readable_string)


def load_policy(path):
    policy = yaml.safe_load(path.read_text())
    if policy['version'] != 1 or set(policy['toolchains']) != {'current', 'msrv'}:
        raise ValueError('unsupported policy/toolchain roles')
    names = set()
    for check in policy['checks']:
        if not re.fullmatch(r'[a-z][a-z0-9-]+', check['name']) or check['name'] in names:
            raise ValueError('invalid or duplicate check name')
        names.add(check['name'])
        if not check['command'] or not set(check['roles']) <= policy['toolchains'].keys() or not check['roles']:
            raise ValueError('missing command or invalid role')
        if type(check['timeout']) is not int or check['timeout'] <= 0:
            raise ValueError('invalid timeout')
        if check.get('completion', 'command') not in {'command', 'libtest', 'trybuild', 'cucumber'}:
            raise ValueError('invalid completion format')
    return policy


def render(policy):
    groups = {role: sorted({check['group'] for check in policy['checks'] if role in check['roles']}) for role in policy['toolchains']}
    shell = ['#!/usr/bin/env bash', LICENSE.rstrip(), '# Generated by tools/ci/generate.py; edit policy.yaml instead.',
             'set -euo pipefail', 'root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)', 'cd "$root"',
             'configuration=""', 'group=""',
             'while (($#)); do', '  case "$1" in',
             '    --configuration) configuration=${2:?missing configuration}; shift 2 ;;',
             '    --group) [[ -z "$group" ]] || exit 2; group=${2:?missing group}; shift 2 ;;',
             '    --all) [[ -z "$group" ]] || exit 2; group=all; shift ;;',
             '    *) printf "Unknown option: %s\\n" "$1" >&2; exit 2 ;;', '  esac', 'done',
             'case "$configuration:$group" in']
    valid = [f'{role}:{group}' for role, items in groups.items() for group in [*items, 'all']]
    shell += ['  ' + '|'.join(valid) + ') ;;', '  *) printf "Choose --configuration current|msrv and --all or --group NAME\\n" >&2; exit 2 ;;', 'esac',
              'if [[ "$configuration" == current && ${UP_RUST_SKIP_TRYBUILD+x} ]]; then',
              '  printf "UP_RUST_SKIP_TRYBUILD is forbidden for the current compiler\\n" >&2; exit 2', 'fi',
              '[[ ! ${RUSTC_BOOTSTRAP+x} ]] || { printf "RUSTC_BOOTSTRAP is forbidden\\n" >&2; exit 2; }',
              'if [[ "$configuration" == msrv ]]; then export UP_RUST_SKIP_TRYBUILD=1; fi',
              'export RUSTFLAGS=-Dwarnings RUSTDOCFLAGS=-Dwarnings',
              'log_root="${CARGO_TARGET_DIR:-target}/ci-logs/$configuration"']
    for role, toolchain in policy['toolchains'].items():
        for check in policy['checks']:
            if role not in check['roles']:
                continue
            command = [arg.format(toolchain=toolchain) for arg in check['command']]
            shell += [f'if [[ "$configuration" == {role} && ( "$group" == all || "$group" == {check["group"]} ) ]]; then',
                      f'  python3 tools/ci/run_check.py --log "$log_root/{check["name"]}.log" --timeout {check["timeout"]} --completion {check.get("completion", "command")} -- {shlex.join(command)}', 'fi']
    workflow = dict(name='Default checks', on={'push': {'branches': ['main']}, 'pull_request': {},
        'workflow_call': {'outputs': {'test_results_url': {'description': 'URL of current-compiler test logs', 'value': '${{ jobs.current-tests.outputs.test_results_url }}'}}},
        'workflow_dispatch': {}}, permissions={'contents': 'read'},
        env={'RUSTFLAGS': '-Dwarnings', 'RUSTDOCFLAGS': '-Dwarnings', 'CARGO_TERM_COLOR': 'always'},
        concurrency={'group': '${{ github.ref }}-${{ github.workflow }}', 'cancel-in-progress': True}, jobs={})
    workflow['jobs']['policy'] = {'runs-on': 'ubuntu-latest', 'steps': [
        {'uses': CHECKOUT, 'with': {'persist-credentials': False}},
        {'run': 'python3 -m pip install -r tools/ci/requirements.txt'},
        {'run': 'python3 tools/ci/generate.py --check'}, {'run': 'python3 -m unittest discover -s tools/ci -p "test_*.py"'},
        {'run': 'bash -n tools/ci/gate.sh'}]}
    for role, selected in groups.items():
        for group in selected:
            steps = [{'uses': CHECKOUT, 'with': {'submodules': 'recursive', 'persist-credentials': False}},
                     {'uses': SETUP, 'with': {'toolchain': policy['toolchains'][role], 'components': 'rustfmt, clippy'}}]
            if group == 'dependency':
                steps.append({'run': 'cargo install --locked cargo-deny --version 0.19.0'})
                steps.append({'name': 'Prepare locked dependency and advisory caches',
                              'run': 'cargo fetch --locked\ncargo deny --locked fetch'})
            steps.append({'run': f'bash tools/ci/gate.sh --configuration {role} --group {group}'})
            job = {'runs-on': 'ubuntu-latest', 'steps': steps}
            if role == 'current' and group == 'tests':
                steps.append({'name': 'Upload test logs', 'id': 'test_results', 'uses': UPLOAD,
                              'with': {'name': 'test-results', 'path': 'target/ci-logs/current/*.log', 'if-no-files-found': 'error'}})
                job['outputs'] = {'test_results_url': '${{ steps.test_results.outputs.artifact-url }}'}
            workflow['jobs'][f'{role}-{group}'] = job
    extras = yaml.safe_load((ROOT / 'tools/ci/workflow-extra.yaml').read_text().replace('@CURRENT_TOOLCHAIN@', policy['toolchains']['current']))
    if set(extras) & workflow['jobs'].keys():
        raise ValueError('extra jobs collide with generated checks')
    workflow['jobs'].update(extras)
    text = yaml.dump(workflow, Dumper=WorkflowDumper, sort_keys=False, width=100)
    for job, requirement in {'current-check': 'build', 'current-style': 'linter',
                             'current-docs': 'api-docs', 'current-tests': 'test'}.items():
        text = text.replace(f'  {job}:\n', f'  # [impl->req~up-language-ci-{requirement}~1]\n  {job}:\n')
    return '\n'.join(shell) + '\n', LICENSE + '# Generated by tools/ci/generate.py; edit policy.yaml or workflow-extra.yaml.\n' + text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    shell, workflow = render(load_policy(ROOT / 'tools/ci/policy.yaml'))
    stale = []
    for path, text in [(ROOT / 'tools/ci/gate.sh', shell), (ROOT / '.github/workflows/check.yaml', workflow)]:
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        print('Stale generated files: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
